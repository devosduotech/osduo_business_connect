#!/usr/bin/env python3
"""Generate self-hosted latin(+rupee) woff2 subsets for the BC theme fonts.

Fetches the per-weight truetype Google serves for an empty User-Agent (a single,
un-split face) and subsets each to the Google `latin` + `latin-ext` ranges plus
U+20B9 (rupee sign, which Google's latin subset omits). Writes the woff2 files
into public/fonts/ and a matching public/css/fonts.css with font-display: swap.
"""
import io
import os
import re
import urllib.request

from fontTools.subset import Options, Subsetter
from fontTools.ttLib import TTFont
from fontTools.varLib.instancer import instantiateVariableFont

APP = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
FONTS_DIR = os.path.join(APP, "osduo_business_connect", "public", "fonts")
CSS_PATH = os.path.join(APP, "osduo_business_connect", "public", "css", "fonts.css")

# family -> weights, matching the cdn request removed from bc_base.html
FAMILIES = {
    "Inter": [400, 500, 600, 700],
    "Lato": [400, 700],
    "Merriweather": [400, 700],
    "Montserrat": [400, 500, 600, 700],
    "Nunito": [400, 600, 700],
    "Open Sans": [400, 600, 700],
    "Playfair Display": [400, 500, 700],
    "Poppins": [400, 500, 600, 700],
    "Raleway": [400, 500, 600, 700],
    "Roboto": [400, 500, 700],
    "Source Sans 3": [400, 600, 700],
    "Space Grotesk": [400, 500, 700],
}

# Google's own latin + latin-ext unicode-ranges (so we stay faithful to what the
# CDN covered) plus U+20B9, which is deliberately added so a typed rupee sign
# renders in the theme font rather than a system fallback.
LATIN = (
    "U+0000-00FF,U+0131,U+0152-0153,U+02BB-02BC,U+02C6,U+02DA,U+02DC,U+0304,"
    "U+0308,U+0329,U+2000-206F,U+2074,U+20AC,U+2122,U+2191,U+2193,U+2212,U+2215,U+FEFF"
)
LATIN_EXT = (
    "U+0100-024F,U+0259,U+1E00-1EFF,U+2020,U+20A0-20AB,U+20AD-20C0,U+2113,"
    "U+2C60-2C7F,U+A720-A7FF"
)
RANGES = f"{LATIN},{LATIN_EXT},U+20B9"

UA = {"User-Agent": ""}  # empty UA => one full truetype face per weight, not split


def expand(range_str):
    out = set()
    for tok in range_str.split(","):
        tok = tok.strip()
        if not tok:
            continue
        m = re.match(r"U\+([0-9A-Fa-f]+)(?:-([0-9A-Fa-f]+))?$", tok)
        if not m:
            raise ValueError(f"bad token {tok!r}")
        lo = int(m.group(1), 16)
        hi = int(m.group(2), 16) if m.group(2) else lo
        out.update(range(lo, hi + 1))
    return sorted(out)


def http(url):
    return urllib.request.urlopen(urllib.request.Request(url, headers=UA), timeout=30).read()


def css_faces(family, weights):
    fam = family.replace(" ", "+")
    w = ";".join(str(x) for x in weights)
    url = f"https://fonts.googleapis.com/css2?family={fam}:wght@{w}"
    body = http(url).decode()
    # each @font-face has font-weight: N and a .ttf src url
    faces = {}
    for block in re.split(r"@font-face\s*\{", body)[1:]:
        wm = re.search(r"font-weight:\s*(\d+)", block)
        sm = re.search(r"url\((https://[^)]+\.ttf)\)", block)
        if wm and sm:
            faces[int(wm.group(1))] = sm.group(1)
    return faces


def slug(family):
    return re.sub(r"[^a-z0-9]+", "-", family.lower()).strip("-")


def _subset_options():
    """Lean subsetter options for UI text.

    Keep the composition/spacing features that accented and multi-script Latin
    need (ccmp, mark/mkmk) plus kerning, but drop stylistic sets, contextual
    alternates and ligature closure — those are what drag a latin-ext face to
    1000+ glyphs. Composites like e-acute stay because they are directly in the
    cmap.
    """
    o = Options()
    o.layout_features = ["ccmp", "kern", "mark", "mkmk"]
    o.name_IDs = ["*"]
    o.legacy_kern = False
    o.notdef_glyph = True
    o.drop_tables = ["DSIG", "PCLT", "LTSH", "VDMX", "hdmx", "EBLC", "EBDT", "EBSC", "STAT"]
    return o


def main():
    unicodes = expand(RANGES)
    os.makedirs(FONTS_DIR, exist_ok=True)
    os.makedirs(os.path.dirname(CSS_PATH), exist_ok=True)
    rules = [
        "/* Self-hosted theme fonts (Phase D). Subset to latin + latin-ext +",
        "   U+20B9 (rupee). font-display: swap avoids blocking first paint.",
        "   Generated by scripts/gen_fonts.py; source fonts are OFL-licensed.",
        "*/",
    ]
    made = []
    for family, weights in FAMILIES.items():
        faces = css_faces(family, weights)
        for w in weights:
            if w not in faces:
                print(f"  ! {family} {w} not offered by Google, skipped")
                continue
            data = http(faces[w])
            font = TTFont(io.BytesIO(data))
            # Google serves the full variable font to an empty UA; instantiate to
            # the requested weight (pins 'wght', defaults the rest) so the subset
            # is a static face, not the whole VF with every master.
            if "fvar" in font:
                axes = {a.axisTag: a.defaultValue for a in font["fvar"].axes}
                if "wght" in axes:
                    axes["wght"] = w
                instantiateVariableFont(font, axes, inplace=True)
            sub = Subsetter(options=_subset_options())
            sub.populate(unicodes=unicodes)
            sub.subset(font)
            fname = f"{slug(family)}-{w}.woff2"
            font.save(os.path.join(FONTS_DIR, fname))
            size = os.path.getsize(os.path.join(FONTS_DIR, fname))
            rules.append(
                "@font-face {\n"
                f"  font-family: '{family}';\n"
                "  font-style: normal;\n"
                f"  font-weight: {w};\n"
                "  font-display: swap;\n"
                f"  src: url('../fonts/{fname}') format('woff2');\n"
                "}"
            )
            made.append((fname, size))
            print(f"  + {fname} ({size // 1024} KB)")
    with open(CSS_PATH, "w") as f:
        f.write("\n".join(rules) + "\n")
    total = sum(s for _, s in made)
    print(f"\nWrote {len(made)} faces, {total / 1024:.0f} KB total -> {CSS_PATH}")
    # verify a rupee glyph survived in one output
    chk = TTFont(os.path.join(FONTS_DIR, "inter-400.woff2"))
    print("rupee in inter-400:", 0x20B9 in chk.getBestCmap())


if __name__ == "__main__":
    main()
