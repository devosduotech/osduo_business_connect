#!/usr/bin/env python3
"""Emit osduo_business_connect/utils/icons.py from fetched SVG sources.

Brands come from Simple Icons (CC0) and render with ``fill="currentColor"``; the
three solid glyphs come from Lucide (ISC) and render with ``stroke="currentColor"``.
The generated module is stdlib-only so it can be registered as a Jinja filter.
Regenerate from the upstream SVGs rather than hand-editing the path data.
"""
import json
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = "/tmp/opencode/icons"
OUT = os.path.normpath(os.path.join(HERE, "..", "osduo_business_connect", "utils", "icons.py"))

ICONS = {
    "facebook": ("facebook.svg", "brand"),
    "instagram": ("instagram.svg", "brand"),
    "linkedin": ("linkedin.svg", "brand"),
    "x": ("x.svg", "brand"),
    "youtube": ("youtube.svg", "brand"),
    "telegram": ("telegram.svg", "brand"),
    "globe": ("lucide-globe.svg", "solid"),
    "link": ("lucide-link.svg", "solid"),
    "briefcase": ("lucide-briefcase.svg", "solid"),
}


def inner_markup(text):
    body = re.search(r"<svg[^>]*>(.*)</svg>", text, re.S).group(1)
    body = re.sub(r"<title>.*?</title>", "", body, flags=re.S)
    body = re.sub(r'\s+class="[^"]*"', "", body)  # drop lucide JS classes
    return body.strip()


HEADER = '''# Copyright (c) 2026, OSDuo and contributors
# For license information, please see license.txt

"""Inline-SVG icon macro for public pages (Phase D, Core Web Vitals).

Replaces the Font Awesome CDN. Brand marks are Simple Icons (CC0), rendered
with ``fill="currentColor"``; the generic glyphs are Lucide (ISC), rendered
with ``stroke="currentColor"``. Generated by ``scripts/build_icons.py`` from the
upstream SVGs.

Stdlib-only, so it is safe to register as a Jinja filter (see ``hooks.py``).
``bc_icon`` maps a stored ``icon_class`` (e.g. ``"fa-brands fa-facebook"``) or a
platform/link_type name to an inline ``<svg>``.
"""

import re

# name -> {"kind": "brand"|"solid", "svg": <inner markup>}
_ICONS = '''

FOOTER = '''

# The svg opening-tag attributes shared by each style.
_ATTRS = {
    "brand": 'fill="currentColor" aria-hidden="true"',
    "solid": (
        'fill="none" stroke="currentColor" stroke-width="2" '
        'stroke-linecap="round" stroke-linejoin="round" aria-hidden="true"'
    ),
}

_MAP = [
    ("linkedin", "linkedin"),
    ("facebook", "facebook"),
    ("instagram", "instagram"),
    ("youtube", "youtube"),
    ("telegram", "telegram"),
    ("globe", "globe"),
    ("website", "globe"),
    ("briefcase", "briefcase"),
    ("portfolio", "briefcase"),
    ("link", "link"),
    ("other", "link"),
]
_FALLBACK = "link"
_X_RE = re.compile(r"(^|[\\s:,])x([\\s:,]|$)")


def resolve_icon(*hints):
    """Canonical icon name for ``icon_class`` / platform / link_type hints."""
    blob = " ".join(h for h in hints if h).lower()
    if "x-twitter" in blob or _X_RE.search(blob):
        return "x"
    for needle, name in _MAP:
        if needle in blob:
            return name
    return _FALLBACK


def bc_icon(icon_class="", platform="", link_type="", label="", style=""):
    """Jinja global: an inline ``<svg>`` glyph for a social/link row.

    Pass the stored ``icon_class`` plus ``platform``/``link_type`` so a record
    with an empty or legacy class still resolves. Falls back to a generic link
    glyph. The markup is returned raw (Frappe disables Jinja autoescape).
    """
    name = resolve_icon(icon_class, platform, link_type)
    kind = _ICONS[name]["kind"]
    inner = _ICONS[name]["svg"]
    style_attr = f' style="{style}"' if style else ""
    cls = f"bc-icon bc-icon-{name}"
    return (
        f'<svg class="{cls}" viewBox="0 0 24 24" width="1em" height="1em" '
        f'{_ATTRS[kind]}{style_attr}>{inner}</svg>'
    )
'''


def main():
    data = {
        name: {"kind": kind, "svg": inner_markup(open(os.path.join(SRC, fn)).read())}
        for name, (fn, kind) in ICONS.items()
    }
    module = HEADER + json.dumps(data, ensure_ascii=False, indent=4) + "\n" + FOOTER
    with open(OUT, "w") as f:
        f.write(module)
    print("wrote", os.path.relpath(OUT, os.path.join(HERE, "..")), "->", len(data), "icons")


if __name__ == "__main__":
    main()
